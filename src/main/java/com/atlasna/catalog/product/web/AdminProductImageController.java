package com.atlasna.catalog.product.web;

import com.atlasna.catalog.media.ObjectStorage;
import com.atlasna.catalog.product.dto.AdminProductResponse;
import com.atlasna.catalog.product.service.ProductImageService;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;
import lombok.RequiredArgsConstructor;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

/** Product photo upload for the back-office (ADMIN and STAFF). See ProductImageService for the three-step flow. */
@RestController
@RequiredArgsConstructor
@PreAuthorize("hasAnyRole('ADMIN','STAFF')")
public class AdminProductImageController {

    private final ProductImageService images;

    public record UploadRequest(@NotNull @Positive Long productId, @NotBlank String contentType, @NotNull @Positive Long sizeBytes) {}

    public record Alt(@Size(max = 200) String fr, @Size(max = 200) String ar) {}

    public record ImageInput(@NotBlank @Size(max = 200) String key, @Valid Alt alt) {}

    public record ImagesRequest(@NotNull @Size(max = ProductImageService.MAX_IMAGES) List<@Valid ImageInput> images) {}

    /** Step 1: a signed, short-lived link to PUT the file to (the key is generated by the server). */
    @PostMapping("/api/admin/uploads/product-image")
    public ObjectStorage.UploadTarget requestUpload(@Valid @RequestBody UploadRequest r) {
        return images.requestUpload(new ProductImageService.UploadRequest(r.productId(), r.contentType(), r.sizeBytes()));
    }

    /** Step 3: the product's photos, in display order (keep existing ones by sending their key back). */
    @PutMapping("/api/admin/products/{id}/images")
    public AdminProductResponse replace(@PathVariable long id, @Valid @RequestBody ImagesRequest r) {
        return images.replaceImages(id, r.images().stream()
                .map(i -> new ProductImageService.ImageRef(i.key(), i.alt() == null ? null : i.alt().fr(), i.alt() == null ? null : i.alt().ar()))
                .toList());
    }
}
